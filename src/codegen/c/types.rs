mod runtime_helpers;

impl CEmitter {
    pub(super) fn c_type(ty: &Type) -> String {
        match ty {
            Type::I8 => "int8_t".into(),
            Type::I16 => "int16_t".into(),
            Type::I32 => "int32_t".into(),
            Type::I64 => "int64_t".into(),
            Type::U8 => "uint8_t".into(),
            Type::U16 => "uint16_t".into(),
            Type::U32 => "uint32_t".into(),
            Type::U64 => "uint64_t".into(),
            Type::Usize => "size_t".into(),
            Type::F32 => "float".into(),
            Type::F64 => "double".into(),
            Type::Bool => "bool".into(),
            Type::Void | Type::Never => "void".into(),
            Type::Str => "zen_str".into(),
            Type::Named(name) | Type::Struct { name, .. } | Type::Enum { name, .. } => {
                c_ident(name)
            }
            Type::Array { elem, .. } => Self::c_type(elem),
            Type::Slice(elem) => format!("{}*", Self::c_type(elem)),
            Type::Ptr(inner) => format!("const {}*", Self::c_type(inner)),
            Type::MutPtr(inner) | Type::RawPtr(inner) => format!("{}*", Self::c_type(inner)),
            Type::Function { params, ret } => {
                let ps: Vec<_> = params.iter().map(Self::c_type).collect();
                format!("{}(*)({})", Self::c_type(ret), ps.join(", "))
            }
            // The result of an async call is a pointer to that function's
            // coroutine frame (ASYNC_PLAN.md milestone 1). Frames are driven
            // generically through their uniform leading `__poll` field, so a
            // `Future<T>` value is held as an opaque `void*` handle.
            Type::Future(_) => "void*".into(),
            Type::Unknown => "void /* unknown */".into(),
        }
    }

    pub(super) fn emit_program(&mut self, program: &TypedProgram) {
        self.line("/* Generated by zen compiler v0.8.0 */");
        self.line("#include <stdint.h>");
        self.line("#include <stdbool.h>");
        self.line("#include <stddef.h>");
        self.line("#include <stdio.h>");
        self.line("#include <stdlib.h>");
        self.line("#include <string.h>");
        self.line("#include <unistd.h>");
        self.blank();

        self.emit_runtime_types();

        for typedef in &program.types {
            let name = c_ident(&typedef.name);
            self.line(&format!("typedef struct {name} {name};"));
        }
        if !program.types.is_empty() {
            self.blank();
        }

        for typedef in order_types_by_value_deps(&program.types) {
            self.emit_type_def(typedef);
            self.blank();
        }

        // Extern C functions (FFI): emit a prototype; the symbol is resolved at
        // link time from a `link:`-ed library. A plain identifier passes through
        // c_func_ident verbatim and matches the real symbol; a name colliding
        // with a C keyword would be rewritten to `zen_<name>` and fail to link
        // — harmless, since no C library can export a keyword-named function.
        // (A clear compile-time guard for that case is a documented follow-up.)
        // Opaque `@extern` C types: a forward `typedef struct N N;`. Used behind
        // pointers (`SDL_Window*`); the real definition comes from a `headers:`
        // include (an identical typedef is a legal C11 redefinition).
        for ty in &program.extern_types {
            let name = c_ident(ty);
            self.line(&format!("typedef struct {name} {name};"));
        }
        if !program.extern_types.is_empty() {
            self.blank();
        }

        for ext in &program.extern_functions {
            let ret = Self::c_type(&ext.return_type);
            let name = c_func_ident(&ext.name);
            let params = extern_param_list(&ext.params);
            self.line(&format!("extern {} {}({});", ret, name, params));
            // Record which args are `Str`, to marshal them to `const char*`.
            let str_args: HashSet<usize> = ext
                .params
                .iter()
                .enumerate()
                .filter(|(_, p)| p.ty == Type::Str)
                .map(|(i, _)| i)
                .collect();
            if !str_args.is_empty() {
                self.extern_str_args.insert(ext.name.clone(), str_args);
            }
        }
        if !program.extern_functions.is_empty() {
            self.blank();
        }

        // Async functions lower to a frame struct + poll fn + constructor; emit
        // their frame typedefs/structs before any prototype so the constructor
        // return type and poll body are complete. (ASYNC_PLAN.md milestone 1.)
        let async_fns: Vec<&TypedFunction> =
            program.functions.iter().filter(|f| f.is_async).collect();
        for func in &async_fns {
            let frame = format!("{}__frame", c_func_ident(&func.name));
            self.line(&format!("typedef struct {frame} {frame};"));
        }
        for func in &async_fns {
            self.emit_async_frame_struct(func);
            self.blank();
        }

        for func in &program.functions {
            let name = c_func_ident(&func.name);
            let params = self.format_params(&func.params);
            if func.is_async {
                // Constructor returns a frame pointer (the `Future<T>` value).
                let frame = format!("{name}__frame");
                self.line(&format!("static bool {name}__poll(void*, void*);"));
                self.line(&format!("{frame}* {name}({params});"));
            } else {
                let ret = Self::c_type(&func.return_type);
                self.line(&format!("{} {}({});", ret, name, params));
            }
        }
        if !program.functions.is_empty() {
            self.blank();
        }

        for global in &program.globals {
            let val = self.emit_expr_inline(&global.value);
            if matches!(global.ty, Type::Function { .. }) {
                self.line(&format!("{} = {val};", c_declarator(&global.ty, &global.name)));
            } else {
                let ty = Self::c_type(&global.ty);
                let name = c_ident(&global.name);
                let qualifier = c_const_qualifier(global.mutable);
                self.line(&format!("{qualifier}{ty} {name} = {val};"));
            }
        }
        if !program.globals.is_empty() {
            self.blank();
        }

        for func in &program.functions {
            if func.is_async {
                self.emit_async_poll(func);
                self.blank();
                self.emit_async_constructor(func);
                self.blank();
            } else {
                self.emit_function(func);
                self.blank();
            }
        }

        if program.entry_point.is_some() {
            self.line("int main(int argc, char** argv) {");
            self.indent();
            self.line("return zen_main();");
            self.dedent();
            self.line("}");
        }
    }

    pub(super) fn emit_type_def(&mut self, typedef: &TypedTypeDef) {
        let name = c_ident(&typedef.name);
        match &typedef.kind {
            TypeDefKind::Struct { fields } => {
                self.line(&format!("struct {} {{", name));
                self.indent();
                for (field_name, field_type) in fields {
                    self.line(&format!("{};", c_declarator(field_type, field_name)));
                }
                self.dedent();
                self.line("};");
            }
            TypeDefKind::Enum { variants } => {
                self.line(&format!("enum {}_Tag {{", name));
                self.indent();
                for variant in variants {
                    self.line(&format!(
                        "{}_{} = {},",
                        name,
                        c_ident(&variant.name),
                        variant.tag
                    ));
                }
                self.dedent();
                self.line("};");
                self.blank();

                self.line(&format!("struct {} {{", name));
                self.indent();
                self.line(&format!("enum {}_Tag tag;", name));

                if variants.iter().any(|v| v.payload.is_some()) {
                    self.line("union {");
                    self.indent();
                    for variant in variants {
                        if let Some(payload) = &variant.payload {
                            self.line(&format!(
                                "{} {};",
                                Self::c_type(payload),
                                c_ident(&variant.name).to_lowercase()
                            ));
                        }
                    }
                    self.dedent();
                    self.line("} data;");
                }
                self.dedent();
                self.line("};");
            }
        }
    }
}

/// Format an `@extern` C prototype's parameters. A `Str` parameter becomes a
/// null-terminated `const char*` (call sites marshal the argument), so the
/// prototype matches idiomatic C string APIs; all other params use the normal
/// declarator.
fn extern_param_list(params: &[TypedParam]) -> String {
    if params.is_empty() {
        return "void".into();
    }
    params
        .iter()
        .map(|p| {
            if p.ty == Type::Str {
                format!("const char* {}", c_ident(&p.name))
            } else {
                c_declarator(&p.ty, &p.name)
            }
        })
        .collect::<Vec<_>>()
        .join(", ")
}

/// Order struct/enum bodies so that a type embedded *by value* in another is
/// defined first — C requires the complete type for a by-value field. Pointer
/// fields only need the forward `typedef`, so they create no ordering edge
/// (and recursive/cyclic pointer types stay legal). A stable topological sort
/// preserves the original order among independent types; any leftover cycle
/// (illegal by-value recursion) falls back to declaration order.
fn order_types_by_value_deps(types: &[TypedTypeDef]) -> Vec<&TypedTypeDef> {
    use std::collections::{HashMap, HashSet};

    let index: HashMap<&str, usize> = types
        .iter()
        .enumerate()
        .map(|(i, t)| (t.name.as_str(), i))
        .collect();

    let mut ordered = Vec::with_capacity(types.len());
    let mut visited = vec![false; types.len()];

    fn visit<'a>(
        i: usize,
        types: &'a [TypedTypeDef],
        index: &HashMap<&str, usize>,
        visited: &mut [bool],
        on_stack: &mut HashSet<usize>,
        ordered: &mut Vec<&'a TypedTypeDef>,
    ) {
        if visited[i] || !on_stack.insert(i) {
            return;
        }
        for dep in by_value_deps(&types[i]) {
            if let Some(&j) = index.get(dep.as_str()) {
                visit(j, types, index, visited, on_stack, ordered);
            }
        }
        on_stack.remove(&i);
        if !visited[i] {
            visited[i] = true;
            ordered.push(&types[i]);
        }
    }

    for i in 0..types.len() {
        visit(i, types, &index, &mut visited, &mut HashSet::new(), &mut ordered);
    }
    ordered
}

/// Names of types embedded by value (directly or through arrays) in a typedef's
/// fields — the dependencies whose definitions must precede this one.
fn by_value_deps(typedef: &TypedTypeDef) -> Vec<String> {
    let mut names = Vec::new();
    let mut collect = |ty: &Type| collect_by_value_names(ty, &mut names);
    match &typedef.kind {
        TypeDefKind::Struct { fields } => {
            for (_, ty) in fields {
                collect(ty);
            }
        }
        TypeDefKind::Enum { variants } => {
            for payload in variants.iter().filter_map(|v| v.payload.as_ref()) {
                collect(payload);
            }
        }
    }
    names
}

fn collect_by_value_names(ty: &Type, names: &mut Vec<String>) {
    match ty {
        Type::Named(name) | Type::Struct { name, .. } | Type::Enum { name, .. } => {
            names.push(name.clone());
        }
        // Arrays embed their element by value; pointers/slices do not.
        Type::Array { elem, .. } => collect_by_value_names(elem, names),
        _ => {}
    }
}
