macro_rules! define_resolver_contract_code {
    ($($variant:ident = $number:expr,)+) => {
        #[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
        #[repr(u16)]
        pub enum ResolverContractCode {
            $($variant = $number,)+
        }

        impl ResolverContractCode {
            pub const ALL: &'static [Self] = &[$(Self::$variant,)+];

            pub(crate) fn number(self) -> String {
                format!("E{:04}", 7000 + self as u16)
            }

            pub(crate) fn slug(self) -> String {
                format!("resolver_contract_e{:04}", 7000 + self as u16)
            }
        }
    };
}

